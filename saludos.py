"""Utilidades sencillas de saludos en español."""


def saludar(nombre: str) -> str:
    """Devuelve un saludo personalizado para ``nombre``."""
    return f"¡Hola, {nombre}!"


def despedir(nombre: str) -> str:
    """Devuelve una despedida personalizada para ``nombre``."""
    return f"¡Hasta pronto, {nombre}!"
